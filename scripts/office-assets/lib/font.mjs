export const FONT_W = 5;
export const FONT_H = 7;

export function fontChars() {
  return Object.keys(G);
}

export function fontGlyph(ch) {
  return G[ch] ?? G["?"];
}

/** Empacota a fonte em um atlas com 16 colunas. Devolve canvas + metadados. */
export function buildFontAtlas(PixelCanvas, colors = { ink: "#eaf2ff" }) {
  const chars = fontChars();
  const cols = 16;
  const cellW = FONT_W + 1;
  const cellH = FONT_H + 1;
  const rows = Math.ceil(chars.length / cols);
  const canvas = new PixelCanvas(cols * cellW, rows * cellH);
  const glyphs = {};
  chars.forEach((ch, index) => {
    const col = index % cols, row = Math.floor(index / cols);
    const ox = col * cellW, oy = row * cellH;
    const rowsData = G[ch];
    for (let y = 0; y < FONT_H; y++) {
      for (let x = 0; x < FONT_W; x++) {
        if (rowsData[y][x] === "1") canvas.px(ox + x, oy + y, colors.ink);
      }
    }
    glyphs[ch] = { x: ox, y: oy, w: FONT_W, h: FONT_H, advance: FONT_W + 1 };
  });
  return { canvas, glyphs, cellW, cellH, lineHeight: FONT_H + 2 };
}
