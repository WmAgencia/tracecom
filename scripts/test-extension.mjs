import assert from "node:assert/strict";
import { readFile, access } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const extension = path.join(root, "extension");
const manifest = JSON.parse(await readFile(path.join(extension, "manifest.json"), "utf8"));
assert.equal(manifest.manifest_version, 3);
assert.equal(manifest.background.service_worker, "background.js");
assert.equal(manifest.action.default_popup, "popup.html");
assert.ok(manifest.host_permissions.includes("https://iqoption.com/*"));
assert.ok(!manifest.host_permissions.includes("<all_urls>"));
assert.ok(!manifest.permissions.includes("scripting"));
for (const name of ["popup.html", "popup.css", "popup.js", "asset-resolver.js", "content.js", "background.js", "local-engine.js", "experiment-runner.js", "iq-page-bridge.js", "downbar.css"]) await access(path.join(extension, name));
const iqContent = manifest.content_scripts.find((entry) => entry.js.includes("content.js") && entry.matches.includes("https://iqoption.com/*"));
assert.ok(iqContent?.js.includes("asset-resolver.js"), "IQ content must load the strict asset resolver before content.js");
const mainBridge = manifest.content_scripts.find((entry) => entry.js.includes("iq-page-bridge.js"));
assert.equal(mainBridge?.run_at, "document_start");
assert.equal(mainBridge?.world, "MAIN");
assert.ok(!manifest.web_accessible_resources, "bridge must not depend on CSP-sensitive DOM injection");
const bridge = await readFile(path.join(extension, "iq-page-bridge.js"), "utf8");
for (const forbidden of ["document.cookie", "localStorage", "sessionStorage", "ssid", "password", "send(", "WebSocket.prototype.send"]) assert.ok(!bridge.toLowerCase().includes(forbidden.toLowerCase()), `Bridge contains forbidden token: ${forbidden}`);
assert.match(bridge, /candle-generated/);
const assetResolver = await readFile(path.join(extension, "asset-resolver.js"), "utf8");
assert.match(assetResolver, /CURRENCIES/);
assert.match(assetResolver, /IQ_OPTION_OTC/);
assert.match(assetResolver, /iq-chart-header-geometry/);
assert.match(assetResolver, /assetDebugCandidates/);
assert.ok(!/OPT-ION/.test(assetResolver), "Asset resolver must not contain the invalid OPT-ION fallback");
const background = await readFile(path.join(extension, "background.js"), "utf8");
assert.match(background, /api\/iq-option\/ingest/);
assert.match(background, /tc\.diagnostics/);
assert.match(background, /TRACE_1M_TIMEFRAME = "1m"/);
assert.match(background, /TRACE_1M_HORIZON = 1/);
assert.match(background, /tc\.iq\.marketAccepted/);
assert.match(background, /tc\.shadowOpen/);
assert.match(background, /localAnalyze/);
assert.match(background, /tcIqMarketStore/);
assert.match(background, /ASSET_MISMATCH/);
assert.match(background, /PRICE_MISMATCH/);
assert.match(background, /WAITING_FOR_ACTIVE_ID_MAPPING/);
assert.match(background, /tcIqAssetDebug/);
assert.match(background, /ProgressiveExperimentRunner/);
assert.match(background, /REMOTE_API_DISABLED/);
assert.match(background, /function remoteFetch/);
const localStart = background.indexOf("async function callAnalyze(");
const localEnd = background.indexOf("async function forwardIqMarket", localStart);
assert.ok(localStart >= 0 && localEnd > localStart, "Caminho local de análise ausente");
assert.ok(!/fetch\(/.test(background.slice(localStart, localEnd)), "Análise local não pode executar fetch remoto");
assert.ok(!/127\.0\.0\.1:8788/.test(background), "Extensão empacotada não pode ter localhost como default");
const runner = await readFile(path.join(extension, "experiment-runner.js"), "utf8");
for (const marker of ["RUN_A_COMPLETE_A80_V1_FROZEN_RUN_B_STARTED", "RUN_B_COMPLETE_A80_V2_FROZEN_RUN_C_STARTED", "RUN_C_COMPLETE_FINAL_SET_FROZEN_RUN_D_STARTED", "RUN_D_COMPLETE_REPORT_READY", "NO_A80_AFTER_RUN_A", "EXPERIMENT_STARTED"]) assert.match(runner, new RegExp(marker));
const localEngine = await readFile(path.join(extension, "local-engine.js"), "utf8");
assert.match(localEngine, /TraceConLocalEngine/);
assert.match(localEngine, /productionDecision: "WAIT"/);
const content = await readFile(path.join(extension, "content.js"), "utf8");
assert.match(content, /return "1m"/);
assert.match(content, /horizon: 1/);
assert.match(content, /1 MIN/);
assert.match(content, /tc\.iq\.marketAccepted/);
assert.match(content, /iqInstrumentRegistry/);
assert.match(content, /assetMismatch/);
assert.match(content, /MutationObserver/);
assert.match(content, /\[TRACE_CON\]\[ASSET_DEBUG\]/);
assert.match(content, /tcShadowEnabled !== false/);
assert.match(content, /LOCAL SHADOW/);
const popup = await readFile(path.join(extension, "popup.html"), "utf8");
for (const label of ["TRACE_1M Local", "Shadow", "Remote API", "IQ Option", "Market Feed", "Abrir IQ Option", "Testar conexão", "Downbar", "Diagnóstico"]) assert.ok(popup.includes(label), `Popup sem ${label}`);
console.log("Extension static checks: PASS");
